using FieldOps.Application.Features.Reports;
using MigraDoc.DocumentObjectModel;
using MigraDoc.DocumentObjectModel.Tables;

namespace FieldOps.Infrastructure.Pdf;

/// <summary>Lays out a <see cref="ReportPdfDocument"/> on landscape pages with a repeated table header and page numbers (reports-workspace BR-15).</summary>
public sealed class MigraDocReportPdfRenderer : IReportPdfRenderer
{
    public byte[] Render(ReportPdfDocument model)
    {
        var (document, section) = PdfSections.Start(model.ReportName, model.OrganizationName, [], null, "Generated by FieldOps");

        section.PageSetup.Orientation = Orientation.Landscape;
        section.PageSetup.LeftMargin = Unit.FromCentimeter(1.5);
        section.PageSetup.RightMargin = Unit.FromCentimeter(1.5);

        var footer = section.Footers.Primary.AddParagraph();
        footer.Format.Alignment = ParagraphAlignment.Center;
        footer.Format.Font.Size = 8;
        footer.AddText("Page ");
        footer.AddPageField();
        footer.AddText(" of ");
        footer.AddNumPagesField();

        PdfSections.Text(section, model.ReportName, 13, bold: true, color: PdfSections.Brand).Format.SpaceBefore = Unit.FromPoint(8);
        PdfSections.Text(section, model.Description, 9.5, color: PdfSections.Muted);

        var meta = new List<(string, string)> { ("Period", model.Period), ("Branch", model.Branch) };
        meta.AddRange(model.Filters.Select(line => (line.Label, line.Value)));
        meta.Add(("Generated", model.Generated.Replace("Generated ", string.Empty, StringComparison.Ordinal)));
        PdfSections.MetaTable(section, meta);

        PdfSections.Heading(section, "Summary");
        var summary = section.AddTable();
        summary.Borders.Bottom.Color = PdfSections.Rule;
        summary.Borders.Bottom.Width = 0.5;
        var showPrevious = model.Summary.Any(metric => metric.Previous is not null);
        summary.AddColumn(Unit.FromCentimeter(9));
        summary.AddColumn(Unit.FromCentimeter(4));

        if (showPrevious)
        {
            summary.AddColumn(Unit.FromCentimeter(4));
        }

        foreach (var metric in model.Summary)
        {
            var row = summary.AddRow();
            row.Cells[0].AddParagraph(metric.Label);
            row.Cells[1].AddParagraph(metric.Current).Format.Alignment = ParagraphAlignment.Right;

            if (showPrevious)
            {
                row.Cells[2].AddParagraph(metric.Previous is null ? string.Empty : "vs " + metric.Previous + " previous")
                    .Format.Alignment = ParagraphAlignment.Right;
            }
        }

        PdfSections.Heading(section, "Chart values");
        Grid(section, model.Chart.Header, model.Chart.Rows, null, 7.5);

        PdfSections.Heading(section, "Report definitions");

        foreach (var definition in model.Definitions)
        {
            var paragraph = section.AddParagraph();
            paragraph.AddFormattedText(definition.Label + ": ", TextFormat.Bold);
            paragraph.AddText(definition.Value);
        }

        if (model.Disclaimer is not null)
        {
            PdfSections.Text(section, model.Disclaimer, 8.5, color: PdfSections.Muted).Format.SpaceBefore = Unit.FromPoint(6);
        }

        PdfSections.Heading(section, "Rows");
        Grid(section, model.Columns, model.Rows, model.Totals, 7);

        return PdfSections.Render(document);
    }

    private static void Grid(
        Section section, IReadOnlyList<string> header, IReadOnlyList<IReadOnlyList<string>> rows, IReadOnlyList<string>? totals, double size)
    {
        var table = section.AddTable();
        table.Borders.Bottom.Color = PdfSections.Rule;
        table.Borders.Bottom.Width = 0.5;
        table.Format.Font.Size = size;

        var width = Unit.FromCentimeter(24.5 / Math.Max(header.Count, 1));

        foreach (var _ in header)
        {
            table.AddColumn(width);
        }

        var head = table.AddRow();
        head.HeadingFormat = true;
        head.Format.Font.Bold = true;
        head.Shading.Color = Color.FromRgb(241, 245, 249);

        for (var index = 0; index < header.Count; index++)
        {
            head.Cells[index].AddParagraph(header[index]);
        }

        foreach (var values in rows)
        {
            var row = table.AddRow();
            row.KeepWith = 0;

            for (var index = 0; index < header.Count; index++)
            {
                row.Cells[index].AddParagraph(index < values.Count ? values[index] : string.Empty);
            }
        }

        if (totals is not null)
        {
            var row = table.AddRow();
            row.Format.Font.Bold = true;

            for (var index = 0; index < header.Count; index++)
            {
                row.Cells[index].AddParagraph(index < totals.Count ? totals[index] : string.Empty);
            }
        }
    }
}
